"""Regenerate every results table used by README.md and the report from evals/results/*.json.
  python -m evals.runners.results_table   ->  evals/results/results_tables.md
Missing inputs are shown as 'pending' (never invented)."""
import json

from evals.runners import harness as H

R = H.RESULTS


def load(name):
    p = R / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, nd=3, pct=False):
    if x is None:
        return "pending"
    if isinstance(x, (int, float)) and pct:
        return f"{x * 100:.1f}%"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def main():
    out = ["# GigBid results tables", "", "_Generated by `python -m evals.runners.results_table` from `evals/results/*.json`._", ""]
    rag = load("rag_variants_offline")
    abl = load("rag_ablation")
    full = next((r for r in (abl or {}).get("results", []) if r["config"].startswith("full")), None)
    props = {t: (load(f"proposals_{t}") or {}).get("summary") for t in ("v0_fixedwriter_v3", "best_fixedwriter_v3", "v0_fixedwriter_v2", "best_fixedwriter_v2", "v0_fixedwriter", "best_fixedwriter", "best_live")}
    judge = (load("judge_scores") or {}).get("sets", {})

    # ---- B5 headline table
    out += ["## B5. V0 vs shipped pipeline", "",
            "| Variant | Evidence Recall@5 | nDCG@10 | Unsupported claims / proposal (before verification) | Judge score (1-5) | GigSim reply rate | p95 latency (s) | Cost / proposal (USD) |",
            "|---|---|---|---|---|---|---|---|"]
    v0 = next((r for r in (rag or {}).get("results", []) if r["variant"] == "v0_naive"), None)
    for label, retr, pt, jt in (("V0 naive dense", v0["overall"] if v0 else None, props.get("v0_fixedwriter_v3") or props["v0_fixedwriter_v2"], judge.get("v0_fixedwriter_v2")),
                                ("Shipped: V8 corrective over V9 skill graph", full, props.get("best_fixedwriter_v3") or props["best_fixedwriter_v2"], judge.get("best_fixedwriter_v2"))):
        live = props.get("best_live") if label.startswith("Shipped") else None
        out.append(f"| {label} | {f(retr and retr['recall@5'])} | {f(retr and retr['ndcg@10'])} | {f(pt and pt['unsupported_per_proposal_before'], 2)} | "
                   f"{f(jt and jt['mean_judge_score'], 2)} | {f(pt and pt['gigsim_reply_rate'], pct=True)} | "
                   f"{f((live or pt) and (live or pt)['p95_latency_s'], 1)} | {f(live and live['mean_cost_usd_per_proposal'], 4)} |")
    out += ["", "Retrieval metrics: `rag_variants_offline.json` (444 scoreable dev jobs), `rag_ablation.json`. Proposal metrics: "
            "`proposals_*_fixedwriter_v2.json` (90 gold-bid jobs, same deterministic writer, so only retrieval differs). Judge: "
            "`judge_scores.json`. Latency / cost of the live-model pipeline: `proposals_best_live.json`.", ""]

    # ---- all variants
    if rag:
        out += ["## B2. All retrieval variants (dev set, 3 personas)", "", "| Variant | Recall@5 | MRR | nDCG@10 | Recall@5 (>= 4 requirements) | p95 latency (s) |", "|---|---|---|---|---|---|"]
        for r in rag["results"]:
            o = r["overall"]
            name = "v8_corrective over v3 rerank (first run, uncalibrated grader threshold 0)" if r["variant"] == "v8_corrective" else r["variant"]
            out.append(f"| {name} | {f(o['recall@5'])} | {f(o['mrr'])} | {f(o['ndcg@10'])} | {f(r['many_requirements(>=4)'].get('recall@5'))} | {f(r['latency_s']['p95'])} |")
        if full:
            out.append(f"| **v8_corrective over v9 (shipped)** | {f(full['recall@5'])} | {f(full['mrr'])} | {f(full['ndcg@10'])} | {f(full['recall@5_many_req'])} | {f(full['p95_latency_s'])} |")
        out += ["", "V6 uses deterministic context headers (LLM context lines did not fit the free-tier token budget); V7 HyDE was not run on the full set for the same reason.", ""]
    if abl:
        out += ["## Ablation of the shipped pipeline", "", "| Configuration | Recall@5 | MRR | nDCG@10 |", "|---|---|---|---|"]
        out += [f"| {r['config']} | {f(r['recall@5'])} | {f(r['mrr'])} | {f(r['ndcg@10'])} |" for r in abl["results"]]
        out += ["", "### By persona (shipped pipeline)", "", "| Persona | Recall@5 | MRR | nDCG@10 |", "|---|---|---|---|"]
        out += [f"| {p} | {f(v['recall@5'])} | {f(v['mrr'])} | {f(v['ndcg@10'])} |" for p, v in full["by_persona"].items()]
        out += ["", "### By job type (shipped pipeline)", "", "| Job type | n | Recall@5 | nDCG@10 |", "|---|---|---|---|"]
        out += [f"| {k} | {v['n']} | {f(v['recall@5'])} | {f(v['ndcg@10'])} |" for k, v in full["by_kind"].items()]
        out.append("")

    # ---- verifier
    ver, ver1 = load("verifier_eval"), load("verifier_eval_v1_rule")
    if ver:
        out += ["## B3. Claim verification", "", "| Rule | Mode | F1 (detect fabrication) | Precision | Recall |", "|---|---|---|---|---|"]
        for tag, d in (("v1 (number/tool mismatch = partly)", ver1), ("v2 shipped (mismatch = unsupported)", ver)):
            for m, v in (d or {}).get("modes", {}).items():
                out.append(f"| {tag} | {m} | {f(v['f1'])} | {f(v['precision'])} | {f(v['recall'])} |")
        out += ["", f"{ver['n_claims']} labelled claims ({', '.join(f'{k} {v}' for k, v in ver['by_kind'].items())}).", ""]
        out += ["Unsupported claims per proposal before -> after verification:", ""]
        for t, s in props.items():
            if s:
                out.append(f"- `{t}`: {f(s['unsupported_per_proposal_before'], 2)} -> {f(s['unsupported_per_proposal_after'], 3)} (n={s['n_drafted']})")
        out.append("")

    # ---- decisions
    dec, sweep, pricing = load("decision_eval_offline"), load("threshold_sweep"), load("pricing_eval")
    if dec:
        o = dec["overall"]
        out += ["## B4. Decisions (600 dev jobs)", "", "| Metric | Value |", "|---|---|"]
        out += [f"| {k} | {f(o[k])} |" for k in ("bid_f1", "bid_precision", "bid_recall", "scam_precision", "scam_recall", "injection_detected", "price_in_fair_band")]
        if sweep:
            best = next(s for s in sweep["sweep"] if s["threshold"] == 0.7)
            out.append(f"| bid_f1 at shipped threshold 0.70 (threshold_sweep.json) | {f(best['bid_f1'])} |")
        if pricing:
            out.append(f"| price in fair band, pricing rule v1 -> v2 (pricing_eval.json, {pricing['n']} jobs) | {f(pricing['old_rule_in_band'])} -> {f(pricing['new_rule_in_band'])} |")
        out += ["", "| Persona | Bid F1 | Scam recall |", "|---|---|---|"]
        out += [f"| {p} | {f(v['bid_f1'])} | {f(v['scam_recall'])} |" for p, v in dec["by_persona"].items()]
        out.append("")

    # ---- R&D A, C, injection, change request, A/B
    a = load("rq_a_tools")
    out += ["## R&D A. Tool granularity (40 tasks, gpt-oss-20b)", "", "| Tool set | Tools | Tool-selection accuracy | Argument accuracy | Tokens / task |", "|---|---|---|---|---|"]
    for k in ("fine", "coarse", "best"):
        v = (a or {}).get("results", {}).get(k)
        out.append(f"| {k} | {v['n_tools'] if v else 'pending'} | {f(v and v['tool_selection_accuracy'])} | {f(v and v['argument_accuracy'])} | {f(v and v['tokens_per_task'], 0)} |")
    c = load("rq_c_architectures")
    out += ["", "## R&D C. Single agent vs supervisor vs hand-built graph", ""]
    if c:
        done = min((c.get("rows_completed") or {"": c["jobs"]}).values())
        size = f"{done} dev jobs" if done == c["jobs"] else f"{done} of {c['jobs']} planned dev jobs completed by every architecture (free-tier daily token cap)"
        out += [f"_{size}, model `{c['model']}` for every architecture. n/a = no bid letters to audit._", "",
                "| Architecture | Bid/skip accuracy | Scams skipped | Unsupported claims / letter | Letters with violations shipped | GigSim reply rate | Rejected tool calls | Mean tokens / job | p95 latency (s) |",
                "|---|---|---|---|---|---|---|---|---|"]
        for k, v in c["results"].items():
            out.append(f"| {k} | {f(v['bid_skip_accuracy'])} | {v['scams_skipped']} | {f(v['unsupported_claims_per_letter'], 2) if v['unsupported_claims_per_letter'] is not None else 'n/a'} | {v['letters_with_violations']} | "
                       f"{f(v['gigsim_reply_rate'], pct=True) if v['gigsim_reply_rate'] is not None else 'n/a'} | {v.get('rejected_tool_calls', 'n/a')} | {f(v['mean_tokens'], 0)} | {f(v['p95_latency_s'], 1)} |")
    else:
        out.append("pending")
    inj = load("injection_eval")
    out += ["", "## E4. Prompt-injection defence", ""]
    if inj:
        out += ["| Metric | Value |", "|---|---|",
                f"| attacks (planted-injection dev jobs) | {inj['n_attacks']} |",
                f"| attack success rate, undefended | {f(inj['attack_success_rate_undefended'], pct=True)} |",
                f"| attack success rate, defended model output | {f(inj['attack_success_rate_defended_model_output'], pct=True)} |",
                f"| attack success rate, defended and shipped (after Compliance Guard) | {f(inj['attack_success_rate_defended_shipped'], pct=True)} |",
                f"| detector recall on planted injections | {f(inj['detection_recall'], pct=True)} |",
                f"| detector false-positive rate on clean posts | {f(inj['detector_false_positive_rate_on_clean_posts'], pct=True)} |"]
    else:
        out.append("pending")
    cr = load("change_request_eval")
    if cr:
        b, a2 = cr["before_change (config 2026-10-27)"], cr["after_change (config 2026-11-02)"]
        out += ["", "## Change request (2 Nov 2026 policy update)", "", "| | Before (old config) | After (config-only change) |", "|---|---|---|",
                f"| Connects cost mispredicted ({b['jobs']} gold-bid jobs) | {f(b['connects_prediction_error_rate'], pct=True)} | {f(a2['connects_prediction_error_rate'], pct=True)} |",
                f"| Blank-answer proposals caught before submit / rejected by marketplace | {b['blank_answers_caught_before_submit']} / {b['rejected_by_marketplace']} | {a2['blank_answers_caught_before_submit']} / {a2['rejected_by_marketplace']} |",
                "", cr["diff"], ""]
    ab = load("ab_test")
    if ab:
        out += ["## X2. Proposal A/B experiment (paired)", "", "| Arm | Reply rate | Mean client score |", "|---|---|---|"]
        out += [f"| {k} | {f(v['reply_rate'], pct=True)} | {f(v['mean_client_score'])} |" for k, v in ab["arms"].items()]
        out += ["", f"{ab['n_pairs']} pairs; discordant {ab['discordant']}; McNemar exact p = {ab['mcnemar_exact_p']}.", ""]
    gap = load("reply_gap_analysis")
    if gap:
        out += ["## Where better retrieval did not raise the reply rate", "", "| Proposal set | must-have coverage | personalisation | specific result | unsupported before | reply rate |", "|---|---|---|---|---|---|"]
        for t in ("v0_fixedwriter", "best_fixedwriter"):
            g = gap[t]
            out.append(f"| {t} | {f(g['must_cov'])} | {f(g['personal'])} | {f(g['specific'])} | {f(g['unsupported_before'], 2)} | {f(g['replied'], pct=True)} |")
        if props["best_fixedwriter_v2"]:
            out.append(f"| best_fixedwriter_v2 (fix: name the requirement next to its proof) | - | - | - | {f(props['best_fixedwriter_v2']['unsupported_per_proposal_before'], 2)} | {f(props['best_fixedwriter_v2']['gigsim_reply_rate'], pct=True)} |")
        out.append("")
    cmp_ = load("model_profiles")
    if cmp_:
        out += ["## Model configurations (open profiles)", "", "| Profile | Proposals | Unsupported before | Reply rate | p95 latency (s) | Mean tokens | List-price USD / proposal |", "|---|---|---|---|---|---|---|"]
        for k, v in cmp_["profiles"].items():
            out.append(f"| {k} | {v['n_drafted']} | {f(v['unsupported_per_proposal_before'], 2)} | {f(v['gigsim_reply_rate'], pct=True) if v['gigsim_reply_rate'] is not None else 'n/a'} | {f(v['p95_latency_s'], 1)} | {f(v['mean_tokens_per_proposal'], 0)} | {f(v['mean_cost_usd_per_proposal'], 5)} |")
        out.append("")
    (R / "results_tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
