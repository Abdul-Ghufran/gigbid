"""Generate docs/TOOLS.md from the live MCP servers (names, read/write, annotations, auth) + third-party servers."""
import asyncio
import os
from pathlib import Path

os.environ.setdefault("LLM_OFFLINE", "1")
from agent.mcp_client import ALLOWLIST  # noqa: E402
from mcp_servers.marketplace.server import mcp as marketplace  # noqa: E402
from mcp_servers.portfolio.server import mcp as portfolio  # noqa: E402
from mcp_servers.workspace.server import mcp as workspace  # noqa: E402

AUTH = {"marketplace": "Bearer: GigBid-signed per-user token (HMAC, 10 min) over HTTP; per-user token bucket 40 req/min; "
                       "upstream credential = user's GigSim token or Upwork OAuth token, decrypted from the encrypted store",
        "portfolio": "Bearer (per-user signed token) over HTTP; none over stdio (local, single user)",
        "workspace": "Bearer (per-user signed token) over HTTP"}


async def main():
    lines = ["# MCP tool inventory", "",
             "Generated by `python tools/gen_tools_doc.py` from the running servers (do not edit by hand). "
             "Schema snapshots: `tests/contract/snapshots/*.json` (CI fails on unintended changes).", "",
             "| Tool | Server | Read / write | readOnly | destructive | idempotent | Idempotency key | dry_run | Used by agents | Auth |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for name, srv in (("marketplace", marketplace), ("portfolio", portfolio), ("workspace", workspace)):
        for t in await srv.list_tools():
            a = t.annotations
            write = not a.readOnlyHint
            props = t.inputSchema.get("properties", {})
            users = sorted(agent for agent, srvs in ALLOWLIST.items() if t.name in srvs.get(name, set()) and agent != "react_baseline")
            lines.append(f"| `{t.name}` | {name} | {'write' if write else 'read'} | {a.readOnlyHint} | {a.destructiveHint} | {a.idempotentHint} | "
                         f"{'required' if 'idempotency_key' in t.inputSchema.get('required', []) else '-'} | {'yes' if 'dry_run' in props else '-'} | "
                         f"{', '.join(users) or '-'} | {AUTH[name].split(';')[0]} |")
        for r in await srv.list_resource_templates():
            lines.append(f"| resource `{r.uriTemplate}` | {name} | read | - | - | - | - | - | host | {AUTH[name].split(';')[0]} |")
        for p in await srv.list_prompts():
            lines.append(f"| prompt `{p.name}` | {name} | - | - | - | - | - | - | host (Claude Desktop / Cursor) | - |")
    lines += ["", "## Auth and transport details", ""] + [f"- **{k}**: {v}." for k, v in AUTH.items()] + [
        "", "## Third-party MCP servers", "",
        "| Server | Used for | Tools used | Trust rationale |", "|---|---|---|---|",
        "| Upwork official MCP (`https://mcp.upwork.com/mcp`, Streamable HTTP, OAuth 2.1) | live marketplace mode, via `mcp_servers/marketplace/adapters/upwork_live.py` | job search, job details, client details, proposal and message **drafts** (mapped in `upwork_tool_map.yaml`) | First-party server operated by Upwork itself; the only sanctioned automation path under Upwork's bot rules; every write is a draft the freelancer confirms on Upwork. |",
        "| GitHub official MCP (`https://api.githubcopilot.com/mcp/`, PAT bearer) | portfolio ingestion of repos (`rag/ingest/github_mcp.py`) | `search_repositories`, `get_file_contents` (read-only) | Operated by GitHub, read-only scopes, used only for the user's own public repositories; content is still treated as untrusted text. |",
        "", "## Agent allowlists (A6)", "", "Defined in `agent/mcp_client.py`; any call outside the list raises `ToolNotAllowed`.", "",
        "| Agent | Allowed tools |", "|---|---|"]
    for agent, srvs in ALLOWLIST.items():
        tools = ", ".join(f"{s}.{t}" for s, ts in srvs.items() for t in sorted(ts)) or "(none)"
        lines.append(f"| {agent} | {tools} |")
    Path(__file__).resolve().parents[1].joinpath("docs", "TOOLS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("docs/TOOLS.md written")


asyncio.run(main())
